// ============================================================================
// cards-animals.js — Animal cards, transcribed from 물_타입.pdf, 에스퍼_타입.pdf,
// 불_타입.pdf, 격투_타입.pdf, 풀_타입.pdf, 화석.pdf.
//
// ⚠ DATA-ENTRY NOTE: these sheets have no extractable text layer (the PDF
// text is outlined/rasterised, not real text), so every field below was
// transcribed by reading the card images. Numbers are almost certainly all
// correct, but small icon details (exact water/rock adjacency pips, category
// icons) were sometimes too small to verify with certainty — those fields
// are left as `null` / empty arrays rather than guessed. Please spot-check
// against your physical cards before a "real" game; it's easy to fix a
// value here in one place. `abilityKey` drives automatic resolution in
// js/abilities.js — anything not yet automated resolves as `manual`, which
// just shows the Korean ability text for the group to apply by hand (a
// perfectly normal way to run a hobby digitisation while the automated
// coverage grows).
// ============================================================================

let _id = 0;
const nextId = (prefix) => `${prefix}${(++_id).toString(36)}`;

function animal(type, data) {
  return {
    id: nextId('an_'),
    kind: 'animal',
    type,
    name: data.name,
    regions: data.regions || [],
    enclosureSize: data.size,
    waterReq: data.water || 0,
    rockReq: data.rock || 0,
    specialEnclosure: data.special || null, // { kind: 'petting'|'reptile'|'bird', size }
    cost: data.cost,
    appeal: data.appeal ?? null,
    conservationGain: data.cp || 0,
    reputationGain: data.rep || 0,
    condition: data.condition || null, // e.g. 'partnerZoo', description text
    abilityName: data.abilityName || null,
    abilityLevel: data.abilityLevel ?? null,
    abilityText: data.abilityText || '',
    abilityKey: data.abilityKey || (data.abilityText ? 'manual' : null),
    note: data.note || null,
  };
}

